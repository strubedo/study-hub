function classify(title) {
  for (const [re, topics, flag] of RULES) {
    if (re.test(title)) return { topics, legacy: flag === 'legacy' };
  }
  return { topics: [], legacy: false };
}

function cleanTitle(t) {
  return t.replace(/^Free CCNA \| /, '').replace(/ \| CCNA 200-301 Complete Course$/, '').replace(/ \| CCNA 200-301 (Day)/, ' | $1').replace(/ \| CCNA (Day)/, ' | $1');
}

const rows = readFileSync(join(root, 'courses/ccna/data/jeremy-playlist.tsv'), 'utf8').trim().split('\n').map((l) => l.split(/\t|\\t/)); // yt-dlp --print may emit a literal "\t"
const videos = rows.map(([id, seconds, title], i) => {
  const t = cleanTitle(title);
  const day = Number(t.match(/Day (\d+)/)?.[1] ?? 0) || null;
  const kind = /Lab/.test(t) ? 'lab' : /Extra/.test(t) ? 'extra' : 'lecture';
  const { topics, legacy } = classify(t);
  return { id, title: t, seconds: Number(seconds) || 0, day, kind, topics, legacy, order: i + 1, channel: "Jeremy's IT Lab", playlist: PLAYLIST };
});

const out = `// GENERATED by scripts/build-videos.mjs — do not edit by hand.
// Jeremy's IT Lab "Free CCNA 200-301 Complete Course" mapped to the v2.0 blueprint.
export const PLAYLIST_URL = 'https://www.youtube.com/playlist?list=${PLAYLIST}';
export default ${JSON.stringify(videos, null, 2)};
`;
writeFileSync(join(root, 'courses/ccna/content/videos.js'), out);
const unmapped = videos.filter((v) => !v.topics.length).map((v) => v.title);
console.log(`Wrote ${videos.length} videos. Unmapped (${unmapped.length}):\n  ${unmapped.join('\n  ')}`);
